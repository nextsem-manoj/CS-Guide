const fs = require('fs');
const path = require('path');

const content = fs.readFileSync(path.join(__dirname, '../src/data/bcaCoursesData.ts'), 'utf8');

// Strip TypeScript annotations to parse the dataset dynamically in Node
let jsContent = content
  .replace(/export interface[\s\S]*?}/g, '')
  .replace(/export const/g, 'const')
  .replace(/:\s*BcaSemester\[\]/g, '');

jsContent += '\nmodule.exports = { bcaSemesters };';

const tempFile = path.join(__dirname, 'temp_bca_data.js');
fs.writeFileSync(tempFile, jsContent);

const { bcaSemesters } = require(tempFile);
try {
  fs.unlinkSync(tempFile);
} catch (e) {}

// Load crawled data
const crawledSem1 = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'sem1_egyankosh_structure.json'), 'utf8')
);

// Clean display names
crawledSem1.forEach(sub => {
  sub.blocks.forEach(block => {
    block.units.forEach(unit => {
      // Decode HTML entities
      unit.displayName = unit.displayName
        .replace(/&#x20;/g, ' ')
        .replace(/&amp;/g, '&')
        .replace(/\s+/g, ' ')
        .trim();
        
      // Strip prefixes like "Unit-1", "Unit 1", "UNit-1", etc.
      unit.displayName = unit.displayName.replace(/^Unit[- ]\d+\s*/i, '').trim();
      unit.displayName = unit.displayName.replace(/^UNit[- ]\d+\s*/i, '').trim();
      
      // Inject interactive tags for BCS-111 (formerly BCS-011)
      if (sub.code === 'BCS-111') {
        if (unit.fileName === 'Unit-1.pdf') {
          unit.isInteractive = true;
          unit.defaultTab = 'home';
        } else if (unit.fileName === 'Unit-2.pdf') {
          unit.isInteractive = true;
          unit.defaultTab = 'functioning';
        }
      }
    });
  });
});

// Update the 1st semester subjects in our semesters array
const sem1Index = bcaSemesters.findIndex(s => s.id === 1);
if (sem1Index !== -1) {
  bcaSemesters[sem1Index].subjects = crawledSem1;
}

// Generate the updated TypeScript file content
const fileTemplate = `// This file is auto-generated by scripts/merge_sem1_data.js. Do not edit manually.

export interface BcaUnit {
  fileName: string;
  displayName: string;
  isInteractive: boolean;
  defaultTab?: string;
}

export interface BcaBlock {
  name: string;
  path: string;
  units: BcaUnit[];
}

export interface BcaSubject {
  code: string;
  name: string;
  isLab: boolean;
  path: string;
  blocks: BcaBlock[];
}

export interface BcaSemester {
  id: number;
  name: string;
  subjects: BcaSubject[];
}

export const bcaSemesters: BcaSemester[] = ${JSON.stringify(bcaSemesters, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '../src/data/bcaCoursesData.ts'), fileTemplate, 'utf8');
console.log("Successfully merged eGyanKosh Semester-1 data into bcaCoursesData.ts!");
